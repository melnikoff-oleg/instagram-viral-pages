#!/usr/bin/env python3
"""Find available Instagram usernames for a concept.

Give it a concept, it asks Claude for ~100 handle ideas, checks every one of
them on Instagram through Apify, remembers what it learned, and prints the
ones that are free. Run it again (or with --rounds N) and the next round
avoids everything already checked and leans away from the styles that were
taken.

  python3 username-finder/find-usernames.py                  # concept = concept/instagram-concept.md, 100 names, 1 round
  python3 username-finder/find-usernames.py --rounds 3       # three rounds, each learning from the last
  python3 username-finder/find-usernames.py --concept "..."  # free-text concept instead of the doc
  python3 username-finder/find-usernames.py --count 50 --style "one invented word, 6-9 letters"
  python3 username-finder/find-usernames.py --max-len 10   # default cap is 13 characters
  python3 username-finder/find-usernames.py --check iconicframes,stolenframes   # just check these
  python3 username-finder/find-usernames.py --dry-run        # generate only, nothing spent on Apify
  python3 username-finder/find-usernames.py --show           # every available name found so far

Keys come from the .env at the repo root: ANTHROPIC_API_KEY (ideas) and
APIFY_API_KEY (checks). A check costs about $0.009, so a 100-name round is
roughly a dollar.

Everything checked lands in username-finder/results/checked.json; the free
ones are also written to username-finder/results/available.md so you can
read them without the script.

The check is the same one Instagram's signup form runs, through the Apify actor
maged120/instagram-username-checker. Profile scrapers are useless for this:
Instagram holds thousands of handles with no public profile (deleted, banned,
reserved), a profile scraper calls those "not found", and the signup form then
says taken. The actor itself gets rate-limited after roughly 45 checks on one
run and silently answers "taken" for everything after that, so handles go
through in runs of 20 with two canaries in each run, one handle that is surely
free and one that is surely taken; if either canary comes back wrong the whole
run is discarded and retried.
"""
import argparse
import concurrent.futures as cf
import datetime as dt
import json
import os
import pathlib
import re
import sys
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
HERE = pathlib.Path(__file__).resolve().parent
RESULTS = HERE / "results"
STORE = RESULTS / "checked.json"
AVAILABLE_MD = RESULTS / "available.md"
CONCEPT_DOC = ROOT / "concept" / "instagram-concept.md"

MODEL = "claude-opus-5-5"
ACTOR = "maged120~instagram-username-checker"   # runs Instagram's own signup availability check
APIFY_BATCH = 20          # the actor is rate-limited after ~45 checks per run; 20 leaves margin
APIFY_WORKERS = 4         # parallel Apify runs; each run has its own proxy session
FREE_CANARY = "zq8vx_k2m9pw"     # nobody has this; if the run says taken, the run was rate-limited
TAKEN_CANARY = "instagram"       # if the run says this is free, the run is lying the other way
VALID = re.compile(r"^[a-z0-9_](?:[a-z0-9._]{0,28}[a-z0-9_])?$")
MAX_LEN = 13             # default cap; Instagram allows 30 but short is the point


# ---------------------------------------------------------------- env & store

def load_env():
    """Read KEY=value lines from ROOT/.env into the environment (existing vars win)."""
    env = ROOT / ".env"
    if not env.exists():
        return
    for line in env.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        os.environ.setdefault(k.strip(), v.strip().strip('"').strip("'"))


def need(key):
    v = os.environ.get(key)
    if not v:
        sys.exit(f"{key} is not set. Put it in {ROOT / '.env'} or export it.")
    return v


def load_store():
    if STORE.exists():
        return json.loads(STORE.read_text())
    return {}


def save_store(store):
    RESULTS.mkdir(parents=True, exist_ok=True)
    STORE.write_text(json.dumps(store, indent=1, ensure_ascii=False, sort_keys=True) + "\n")
    write_available_md(store)


def write_available_md(store):
    rows = sorted((h, r) for h, r in store.items() if r["status"] == "available")
    lines = ["# Available Instagram usernames", "",
             f"{len(rows)} free of {len(store)} checked. Regenerated by find-usernames.py; "
             "edit checked.json, not this file.", ""]
    by_round = {}
    for h, r in rows:
        by_round.setdefault(r.get("round", "manual"), []).append((h, r))
    for rnd in sorted(by_round, key=str, reverse=True):
        lines.append(f"## {rnd}")
        lines.append("")
        for h, r in by_round[rnd]:
            why = f" — {r['why']}" if r.get("why") else ""
            ver = " (confirmed by hand)" if r.get("verified") else ""
            lines.append(f"{h}{ver}{why}")
            lines.append("")
    AVAILABLE_MD.write_text("\n".join(lines))


# ---------------------------------------------------------------- ideas

def clean(handle, max_len=30):
    """Lowercase, strip @, and return the handle if Instagram would accept it and it fits, else None."""
    h = handle.strip().lstrip("@").lower()
    if VALID.match(h) and ".." not in h and len(h) <= max_len:
        return h
    return None


SYSTEM = """You name Instagram accounts. You are given a concept for a theme page and you
return candidate usernames that a person would actually be happy to put on the profile.

What a good handle is here:
- lowercase letters, maybe an underscore or a period; digits only when they mean something
- never longer than the character limit you are given; shorter is better if it still carries the idea
- a single period or underscore inside the handle is welcome when it helps it read (brake.bloom, gt_dusk)
- easy to say out loud and to type from memory after hearing it once
- it should feel like the concept's world, not describe it; no "official", "page", "daily", "hub", "the_"
- no celebrity, brand or trademark names as the whole handle (car model names inside a longer handle are fine)
- every candidate is different in kind from the others: spread across styles such as
  two-word compounds, one invented word, a phrase from the world of the concept, a
  place-and-object pairing, a cinematic or film-vocabulary word, a quiet poetic word,
  a short all-caps-able word, something playful

The obvious ones are always taken. Assume any single plain English word or any
plain "<topic><noun>" combination is gone and aim for names that sound inevitable
but that nobody has registered. If you are told which handles were already taken,
read them as evidence of what is crowded and move away from those shapes. If you
are told which are already available, do not repeat them and look for other styles.

Return exactly the number of candidates requested, each with a one-line reason
written as a dry, specific note (what it evokes, why it fits), not marketing copy."""

SCHEMA = {
    "type": "object",
    "properties": {
        "candidates": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "handle": {"type": "string"},
                    "why": {"type": "string"},
                },
                "required": ["handle", "why"],
                "additionalProperties": False,
            },
        }
    },
    "required": ["candidates"],
    "additionalProperties": False,
}


def generate(concept, count, store, style=None, max_len=MAX_LEN):
    """Ask Claude for `count` fresh candidates that are not in `store`."""
    import anthropic

    client = anthropic.Anthropic(api_key=need("ANTHROPIC_API_KEY"))
    taken = sorted(h for h, r in store.items() if r["status"] == "taken")
    free = sorted(h for h, r in store.items() if r["status"] == "available")
    parts = [f"Concept:\n\n{concept.strip()}\n",
             f"Hard limit: every handle is at most {max_len} characters.\n"]
    if style:
        parts.append(f"Style constraint for this round: {style}\n")
    if taken:
        parts.append("Already checked and TAKEN (do not repeat, treat as crowded territory):\n"
                     + ", ".join(taken[-400:]) + "\n")
    if free:
        parts.append("Already found AVAILABLE (do not repeat; go for different styles):\n"
                     + ", ".join(free) + "\n")
    # Ask for a few extra so that duplicates and invalid handles still leave `count`.
    parts.append(f"Give {count + max(10, count // 4)} candidates.")

    resp = client.beta.messages.create(
        model=MODEL,
        max_tokens=16000,
        betas=["server-side-fallback-2026-07-01"],
        fallbacks="default",
        output_config={"effort": "high", "format": {"type": "json_schema", "schema": SCHEMA}},
        system=SYSTEM,
        messages=[{"role": "user", "content": "\n".join(parts)}],
    )
    if resp.stop_reason == "refusal":
        sys.exit(f"Claude declined the request: {resp.stop_details}")
    text = next(b.text for b in resp.content if b.type == "text")
    seen, out = set(), []
    for c in json.loads(text)["candidates"]:
        h = clean(c["handle"], max_len)
        if not h or h in seen or h in store:
            continue
        seen.add(h)
        out.append((h, c["why"].strip()))
    return out[:count]


# ---------------------------------------------------------------- checks

def apify_run(handles, token):
    """One actor run. Returns {handle: True|False} for the handles it answered, or None if the run failed."""
    url = (f"https://api.apify.com/v2/acts/{ACTOR}/run-sync-get-dataset-items"
           f"?token={token}&timeout=300&clean=1")
    body = json.dumps({"usernames": handles}).encode()
    req = urllib.request.Request(url, data=body, headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=420) as r:
            items = json.load(r)
    except urllib.error.HTTPError as e:
        print(f"  apify {e.code}: {e.read().decode(errors='replace')[:200]}", file=sys.stderr)
        return None
    except (urllib.error.URLError, TimeoutError, OSError, ValueError) as e:
        print(f"  apify failed: {e}", file=sys.stderr)
        return None
    if not isinstance(items, list):
        print(f"  apify: {json.dumps(items)[:200]}", file=sys.stderr)
        return None
    out = {}
    for it in items:
        h = (it.get("username") or "").lower()
        if h and not it.get("error") and isinstance(it.get("available"), bool):
            out[h] = it["available"]
    return out


def apify_batch(handles, token, attempts=2):
    """Check up to APIFY_BATCH handles with canaries; retry when a run was rate-limited."""
    for attempt in range(attempts):
        res = apify_run([TAKEN_CANARY] + handles + [FREE_CANARY], token)
        if res is None:
            continue
        if res.get(FREE_CANARY) is not True or res.get(TAKEN_CANARY) is not False:
            last = attempt + 1 == attempts
            print(f"  run was rate-limited (canaries: free={res.get(FREE_CANARY)}, "
                  f"taken={res.get(TAKEN_CANARY)}), " + ("leaving these unknown" if last else "retrying"),
                  file=sys.stderr)
            continue
        return {h: ("available" if res[h] else "taken") if h in res else "unknown" for h in handles}
    return {h: "unknown" for h in handles}


def check(handles):
    """Check every handle with Instagram's signup check. Returns {handle: available|taken|unknown}."""
    token = need("APIFY_API_KEY")
    batches = [handles[i:i + APIFY_BATCH] for i in range(0, len(handles), APIFY_BATCH)]
    out = {}
    with cf.ThreadPoolExecutor(max_workers=APIFY_WORKERS) as ex:
        for res in ex.map(lambda b: apify_batch(b, token), batches):
            out.update(res)
    return out


# ---------------------------------------------------------------- rounds

def run_round(concept, count, store, round_tag, style=None, dry_run=False, max_len=MAX_LEN):
    print(f"\n== {round_tag}: asking Claude for {count} candidates ...", flush=True)
    ideas = generate(concept, count, store, style, max_len)
    print(f"   {len(ideas)} fresh, valid handles")
    if dry_run:
        for h, why in ideas:
            print(f"   ? @{h:<24} {why}")
        return []

    handles = [h for h, _ in ideas]
    print(f"   checking {len(handles)} with Instagram's signup check through Apify "
          f"({len(handles) // APIFY_BATCH + (len(handles) % APIFY_BATCH > 0)} runs) ...", flush=True)
    status = check(handles)
    now = dt.datetime.now().isoformat(timespec="seconds")
    for h, why in ideas:
        store[h] = {"status": status.get(h, "unknown"), "why": why, "checker": "signup",
                    "round": round_tag, "checked_at": now}
    save_store(store)

    free = [(h, why) for h, why in ideas if status.get(h) == "available"]
    unknown = [h for h in handles if status.get(h) == "unknown"]
    print(f"\n   {len(free)} available, {len(handles) - len(free) - len(unknown)} taken, "
          f"{len(unknown)} unknown\n")
    for h, why in free:
        print(f"   ✓ @{h:<24} {why}")
    if unknown:
        print(f"\n   unknown (Apify gave no verdict, re-run with --check to retry): "
              + ", ".join(unknown))
    return free


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog=__doc__)
    ap.add_argument("--concept", help="concept as free text; default is the concept doc")
    ap.add_argument("--concept-file", default=str(CONCEPT_DOC),
                    help="file to read the concept from when --concept is not given")
    ap.add_argument("--count", type=int, default=100, help="candidates per round (default 100)")
    ap.add_argument("--rounds", type=int, default=1, help="how many rounds to run now (default 1)")
    ap.add_argument("--style", help="extra constraint for the generator, e.g. 'one invented word'")
    ap.add_argument("--max-len", type=int, default=MAX_LEN,
                    help=f"longest handle to accept, default {MAX_LEN} (Instagram allows 30)")
    ap.add_argument("--check", help="comma-separated handles to check directly, no generation")
    ap.add_argument("--dry-run", action="store_true", help="generate ideas only, no Apify calls")
    ap.add_argument("--show", action="store_true", help="print every available handle found so far")
    ap.add_argument("--recheck", action="store_true",
                    help="re-check every stored handle whose verdict did not come from the signup check")
    args = ap.parse_args()

    load_env()
    store = load_store()

    if args.show:
        free = sorted(h for h, r in store.items() if r["status"] == "available")
        print(f"{len(free)} available of {len(store)} checked (see {AVAILABLE_MD}):\n")
        for h in free:
            print(f"  @{h:<24} {store[h].get('why', '')}")
        return

    if args.recheck:
        args.check = ",".join(h for h, r in store.items()
                              if r.get("checker") != "signup" and r["status"] != "taken")
        if not args.check:
            print("nothing to re-check"); return
        print(f"re-checking {args.check.count(',') + 1} handles ...")

    if args.check:
        handles = []
        for raw in args.check.split(","):
            h = clean(raw)
            if h:
                handles.append(h)
            else:
                print(f"  skipping '{raw.strip()}': not a valid Instagram handle")
        status = check(handles)
        now = dt.datetime.now().isoformat(timespec="seconds")
        for h in handles:
            prev = store.get(h, {})
            store[h] = {**prev, "status": status[h], "why": prev.get("why", ""), "checker": "signup",
                        "round": prev.get("round", "manual"), "checked_at": now}
            mark = {"available": "✓", "taken": "✗"}.get(status[h], "?")
            print(f"  {mark} @{h:<24} {status[h]}")
        save_store(store)
        return

    concept = args.concept
    if not concept:
        path = pathlib.Path(args.concept_file)
        if not path.exists():
            sys.exit(f"No --concept given and {path} does not exist.")
        concept = path.read_text()

    existing = {r.get("round", "") for r in store.values()}
    n = 1
    while any(str(t).startswith(f"round-{n:03d}") for t in existing):
        n += 1
    all_free = []
    for i in range(args.rounds):
        tag = f"round-{n + i:03d}-{dt.date.today().isoformat()}"
        all_free += run_round(concept, args.count, store, tag, args.style, args.dry_run,
                              args.max_len)

    if not args.dry_run:
        total_free = sum(1 for r in store.values() if r["status"] == "available")
        print(f"\n{len(all_free)} new available this run, {total_free} available in total "
              f"({len(store)} checked). Full list: {AVAILABLE_MD}")
        print("Run again for another round; it will avoid everything checked so far.")


if __name__ == "__main__":
    main()
